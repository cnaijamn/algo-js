/**
 * 黒体放射 black body radiation.
 */
export { blackbody as default };

/**
 * 黒体放射.
 * @param {number} t - 温度[K]
 * @return {number[]} RGB
 */
function blackbody(t/*temperature[K]*/) {
  let xyz = blackbodyXYZ(t),
      rgb = toRGB(xyz[0], xyz[1], xyz[2]);

  return [
    parseInt(rgb[0] * 255.0),
    parseInt(rgb[1] * 255.0),
    parseInt(rgb[2] * 255.0),
  ];
}

/**
 * 黒体放射(XYZ).
 * @param {number} t - 温度[K]
 * @return {number[]} XYZ
 */
function blackbodyXYZ(t/*temperature[K]*/) {
  let sx = 0.0, sy = 0.0, sz = 0.0;

  for (let i of CMF) {
    let spd = planckLaw(i.lambda, t);
    sx += (spd * i.cmf[0]);
    sy += (spd * i.cmf[1]);
    sz += (spd * i.cmf[2]);
  }
  let max = Math.max(sx, sy, sz);
  return (max == 0) ? [0, 0, 0]
    : [sx / max, sy / max, sz / max];
}

function toRGB(x, y, z) {
  return [
    clamp(( 3.240970 * x + -1.537383 * y + -0.498611 * z), 0.0, 1.0),
    clamp((-0.969244 * x +  1.875968 * y +  0.041555 * z), 0.0, 1.0),
    clamp(( 0.055630 * x + -0.203977 * y +  1.056972 * z), 0.0, 1.0)
  ];
}

function clamp(n, lower, upper) {
  return Math.max(lower, Math.min(n, upper));
}

const h = 6.62606896e-34; // Plank constant
const c = 2.99792458e+8;  // Speed of light
const k = 1.38064880e-23; // Boltzmann constant
const arg1 = 2 * Math.PI * h * c * c;
const arg2 = (h * c) / k;

function planckLaw(lambda/*wavelength[m/s]*/, t/*temperature[K]*/) {
  let lambda5 = lambda * lambda * lambda * lambda * lambda;
  return (arg1 / lambda5) / (Math.exp(arg2 / (lambda * t)) - 1.0);
}

